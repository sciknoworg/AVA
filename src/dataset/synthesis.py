from transformers import AutoModelForCausalLM, AutoTokenizer
import os
import json

def load_synthesizer_llm(model_id):
    print(f"Loading model {model_id}...")
    tokenizer = AutoTokenizer.from_pretrained(model_id, padding_side="left")
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    model = AutoModelForCausalLM.from_pretrained(
        model_id,
        device_map="auto",
        torch_dtype="auto",
        attn_implementation="eager"
    )
    return model, tokenizer

def format_subgraph_for_prompt(subgraph: dict) -> str:
    lines = ["Entities and their Definitions:"]
    for node, label in subgraph.get("node_labels", {}).items():
        comment = subgraph.get("node_comments", {}).get(node, "No definition provided.")
        lines.append(f" - {label} ({node}): {comment}")

    lines.append("\nRelationships (Triples):")
    for t in subgraph.get("triples", []):
        lines.append(f" - {t['subject_label']} --[{t['predicate_label']}]--> {t['object_label']}")

    return "\n".join(lines)


def generate_triplets_batch(subgraph_texts: list, model, tokenizer) -> list:
    prompts = []
    for subgraph_text in subgraph_texts:
        prompt = f"""<task>
The following content represents a structural sub-graph extracted from a formal knowledge ontology, detailing entities, their definitions, and their semantic relationships (triples).
</task>

<objective>
Synthesize a high-quality dataset of natural language sentence triplets (Anchor, Positive, Negative). This dataset will be utilized for contrastive learning to fine-tune an embedding model (e.g., a Sentence-Transformer) for semantic representation and ontology alignment.
</objective>

<guidelines>
Guidelines for Triplet Generation:
1. Anchor: Formulate a clear, unambiguous declarative sentence that reflects a true fact, definition, or exact relation directly asserted explicitly in the provided sub-graph.
2. Positive: Construct a semantically equivalent paraphrase of the Anchor. This sentence must preserve the exact factual meaning but utilize morphological variations, synonyms, or alternative syntactic structures (e.g., active versus passive voice) to encourage robust semantic representation.
3. Negative: Construct a 'hard negative' statement. This sentence must exhibit high lexical overlap with the Anchor (employing similar entities, relations, or vocabulary from the ontology domain) but assert a factually incorrect relationship, a contradictory definition, or pair disjoint entities. It must serve as a difficult distractor for the embedding model.
</guidelines>

<output-format>
- Generate exactly 5 unique, diverse triplets derived directly from the provided sub-graph.
- Output the result strictly as a valid JSON array of objects, with the exact keys: "anchor", "positive", and "negative".

Example Output:
[
  {{
    "anchor": "A relation interval indicates the time duration during which an agent relationship occurs.",
    "positive": "The timeframe that a connection between entities persists is known as its relation interval.",
    "negative": "A relation interval is an individual or group that participates in a relationship."
  }},
  ...
]
</output-format>

<input-subgraph>
{subgraph_text}
</input-subgraph>
"""
        prompts.append(prompt)

    formatted_texts = []
    for p in prompts:
        messages = [
            {"role": "system", "content": "You are a helpful assistant."},
            {"role": "user", "content": p}
        ]
        text = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True
        )
        formatted_texts.append(text)

    model_inputs = tokenizer(formatted_texts, return_tensors="pt", padding=True).to(model.device)

    generated_ids = model.generate(
        **model_inputs,
        max_new_tokens=1500,
        temperature=0.7,
        do_sample=True,
        pad_token_id=tokenizer.eos_token_id
    )
    input_len = model_inputs.input_ids.shape[1]
    generated_ids = [
        output_ids[input_len:] for output_ids in generated_ids
    ]
    responses = tokenizer.batch_decode(generated_ids, skip_special_tokens=True)

    return responses


def extract_json_with_openai(raw_text: str, client, model) -> list:

    prompt = f"""You are a data extraction assistant. I will provide you with raw text generated by a local AI model.
Your task is to parse out the generated contrastive sentence triplets and call the provided function to extract them.
If the text cuts off or is incomplete, extract as many complete and valid triplets as possible.

Raw Model Output:
{raw_text}
"""

    tools = [
        {
            "type": "function",
            "function": {
                "name": "extract_triplets",
                "description": "Extracts contrastive sentence triplets from the given text.",
                "parameters": {
                    "type": "object",
                    "properties": {
                        "triplets": {
                            "type": "array",
                            "items": {
                                "type": "object",
                                "properties": {
                                    "anchor": {"type": "string"},
                                    "positive": {"type": "string"},
                                    "negative": {"type": "string"}
                                },
                                "required": ["anchor", "positive", "negative"]
                            }
                        }
                    },
                    "required": ["triplets"]
                }
            }
        }
    ]

    response = client.chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": prompt}],
        temperature=0.0,
        tools=tools,
        tool_choice={"type": "function", "function": {"name": "extract_triplets"}}
    )

    message = response.choices[0].message
    if message.tool_calls:
        try:
            arguments = message.tool_calls[0].function.arguments
            data = json.loads(arguments)
            return data.get("triplets", [])
        except json.JSONDecodeError:
            print("Error: OpenAI failed to return decodable JSON from tool call.")
            return []

    print("Error: OpenAI did not return a tool call.")
    return []


def synthesize_data(ontology, model, tokenizer, openai_client, openai_model, strategy='bfs', data_dir='data'):
    manifest_path = os.path.join(data_dir, ontology, strategy, "manifest.json")
    if not os.path.exists(manifest_path):
        print(f"Error: Manifest not found at {manifest_path}")
        return

    out_file = os.path.join(data_dir, ontology, f"{strategy}_synthetic_triplets.json")

    with open(manifest_path, "r") as f:
        manifest = json.load(f)

    subgraphs_list = manifest.get("subgraphs", [])
    if not subgraphs_list:
        print("No subgraphs found in manifest.")
        return

    print(f"Found {len(subgraphs_list)} subgraphs in {manifest_path}")

    all_triplets = []
    batch_size = 4

    for i in range(0, len(subgraphs_list), batch_size):
        batch_entries = subgraphs_list[i:i + batch_size]
        batch_sg_ids = []
        batch_texts = []

        for entry in batch_entries:
            sg_file = entry.get("file")
            if not os.path.exists(sg_file):
                sg_file = os.path.join(os.path.dirname(manifest_path), os.path.basename(sg_file))
                if not os.path.exists(sg_file):
                    print(f"Skipping missing file: {sg_file}")
                    continue

            with open(sg_file, "r") as f:
                subgraph = json.load(f)

            sg_id = subgraph.get("subgraph_id", "unknown")
            batch_sg_ids.append(sg_id)
            batch_texts.append(format_subgraph_for_prompt(subgraph))

        if not batch_texts:
            continue

        print(f"\n--- Processing batch of {len(batch_texts)} subgraphs: {batch_sg_ids} ---")

        try:
            print("Generating raw triplets using local Qwen model...")
            raw_responses = generate_triplets_batch(subgraph_texts=batch_texts, model=model, tokenizer=tokenizer)

            for sg_id, raw_text_response in zip(batch_sg_ids, raw_responses):
                print(f"Extracting and validating JSON format using OpenAI for {sg_id}...")
                triplets = extract_json_with_openai(raw_text=raw_text_response, client=openai_client, model=openai_model)

                if not triplets:
                    print(f"Warning: No valid triplets extracted for {sg_id}.")
                    continue

                # Annotate triplets with subgraph provenance
                for t in triplets:
                    t["subgraph_id"] = sg_id

                all_triplets.extend(triplets)
                print(f"Successfully added {len(triplets)} triplets from {sg_id}.")

            # Incrementally save to disk in case it crashes
            with open(out_file, "w") as f:
                json.dump(all_triplets, f, indent=2)

        except Exception as e:
            print(f"An error occurred while processing batch {batch_sg_ids}: {e}")

    print(f"\nDone! Synthesized and extracted a total of {len(all_triplets)} valid triplets.")
    print(f"Saved to {out_file}")